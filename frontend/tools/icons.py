#!/usr/bin/env python3
"""Generate src/lib/icons.ts from lucide-static SVGs. Usage: icons.py <lucide icons dir>"""
import re, sys
from pathlib import Path
NAMES = """layout-dashboard link chart-column activity qr-code globe arrow-left-right key-round server settings search plus
copy check x chevron-down chevron-right chevron-left chevron-up ellipsis ellipsis-vertical external-link pencil trash-2 star
archive lock tag list-filter sliders-horizontal columns-3 download upload refresh-cw circle-check circle-alert triangle-alert
info circle-x clock calendar eye eye-off sun moon monitor log-out user shield bell history split zap arrow-up-right
arrow-down-right trending-up trending-down panel-left command database file-text hourglass ban gauge cpu hard-drive link-2-off
copy-plus rotate-ccw smartphone tablet bot languages palette image grip-vertical arrow-up-down loader-circle menu circle-pause
circle-dot calendar-clock shield-check webhook brush-cleaning sparkles mouse-pointer-click file-down file-up circle-help
keyboard play square-pen globe-lock arrow-right corner-down-right""".split()
src = Path(sys.argv[1])
out = ['// Generated by tools/icons.py from lucide-static (ISC License, Copyright (c) Lucide Icons and Contributors).',
       '// Inner SVG markup on a 24-unit grid. Icon.svelte applies one shared stroke width.',
       'export const icons = {']
for n in NAMES:
    s = (src / f'{n}.svg').read_text()
    body = s[s.index('>', s.index('<svg')) + 1:s.rindex('</svg>')]
    body = re.sub(r'\s*/>', '/>', re.sub(r'\s+', ' ', body)).replace('> <', '><').strip()
    out.append(f"  '{n}': '{body}',")
out += ['} as const;', '', 'export type IconName = keyof typeof icons;', '']
(Path(__file__).resolve().parent.parent / 'src/lib/icons.ts').write_text('\n'.join(out))
print(len(NAMES), 'icons')
